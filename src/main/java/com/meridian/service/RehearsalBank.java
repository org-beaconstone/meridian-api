package com.meridian.service;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.meridian.domain.*;
import com.meridian.payment.MethodCatalog;
import com.meridian.payment.PaymentProvider;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.http.HttpStatus;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Service;
import org.springframework.transaction.support.TransactionTemplate;
import org.springframework.web.server.ResponseStatusException;
import javax.crypto.Mac;
import javax.crypto.spec.SecretKeySpec;
import java.nio.charset.StandardCharsets;
import java.security.MessageDigest;
import java.time.Instant;
import java.util.*;
import java.util.function.Supplier;

/** Single-instance synthetic ledger. One monitor is held until every transaction commits. */
@Service
public class RehearsalBank {
  public record Payment(String recipientId, Long amountMinor, String method, String note, String scenario) {}
  public record Limit(String category, Long limitMinor) {}
  public record Callback(String sessionId, String eventId, String paymentId, String status) {}
  public record IntentRequest(String recipientId, Long amountMinor, String descriptor, String corridor, String note, String catalogVersion, String scenario) {}
  public record StoredIntent(String recipientId, long amountMinor, String method, String note, String descriptor, String corridor, String catalogVersion) {}
  public record IntentResult(int httpStatus, Map<String,Object> body) {}
  private record Intent(String id, String room, String key, String payload, String status, String provider, long amount) {}
  private final JdbcTemplate db;
  private final TransactionTemplate tx;
  private final ObjectMapper json;
  private final FixtureService fixture;
  private final Map<String, PaymentProvider> providers;
  private final String webhookSecret;

  public RehearsalBank(JdbcTemplate db, TransactionTemplate tx, ObjectMapper json, FixtureService fixture,
    List<PaymentProvider> providers, @Value("${meridian.webhook.secret:}") String secret) {
    this.db=db; this.tx=tx; this.json=json; this.fixture=fixture; this.webhookSecret=secret;
    this.providers=new HashMap<>(); providers.forEach(p -> this.providers.put(p.getProviderId(),p));
    db.execute("CREATE TABLE IF NOT EXISTS meridian_rooms (room VARCHAR(64) PRIMARY KEY, state_json CLOB NOT NULL)");
    db.execute("CREATE TABLE IF NOT EXISTS meridian_intents (payment_id VARCHAR(64) PRIMARY KEY, room VARCHAR(64) NOT NULL, client_key VARCHAR(100) NOT NULL, payload CLOB NOT NULL, phase VARCHAR(20) NOT NULL, provider VARCHAR(20) NOT NULL, amount BIGINT NOT NULL, UNIQUE(room,client_key))");
    db.execute("CREATE TABLE IF NOT EXISTS meridian_callbacks (room VARCHAR(64), provider VARCHAR(20), event_id VARCHAR(100), payload_hash VARCHAR(64) NOT NULL, PRIMARY KEY(room,provider,event_id))");
    db.execute("CREATE TABLE IF NOT EXISTS meridian_audit (sequence BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, room VARCHAR(64), event_json CLOB)");
  }
  private <T> T atomic(Supplier<T> action) { return tx.execute(s -> action.get()); }
  public static void check(boolean valid, String message) { if(!valid) throw new ResponseStatusException(HttpStatus.BAD_REQUEST,message); }
  private void room(String value) { check(value!=null && value.matches("[A-Za-z0-9_-]{3,64}"),"Invalid rehearsal session"); }
  private String encode(Object value) { try { return json.writeValueAsString(value); } catch(Exception e) { throw new IllegalStateException(e); } }
  private <T> T decode(String value, Class<T> type) { try { return json.readValue(value,type); } catch(Exception e) { throw new IllegalStateException(e); } }
  private BankState read(String room) {
    var found=db.query("SELECT state_json FROM meridian_rooms WHERE room=?",(r,n)->r.getString(1),room);
    if(found.isEmpty()) { var state=fixture.loadInitialState(); db.update("INSERT INTO meridian_rooms(room,state_json) VALUES(?,?)",room,encode(state)); return state; }
    return decode(found.getFirst(),BankState.class);
  }
  private void save(String room,BankState state) { db.update("UPDATE meridian_rooms SET state_json=? WHERE room=?",encode(state),room); }
  private void audit(String room,String type,String id,String provider) { db.update("INSERT INTO meridian_audit(room,event_json) VALUES(?,?)",room,encode(Map.of("type",type,"paymentId",id,"provider",provider,"timestamp",Instant.now().toString()))); }
  public synchronized BankState state(String room) { room(room); return atomic(()->read(room)); }
  public synchronized Map<String,Object> reset(String room) { room(room); return atomic(()->{
    db.update("DELETE FROM meridian_callbacks WHERE room=?",room); db.update("DELETE FROM meridian_intents WHERE room=?",room); db.update("DELETE FROM meridian_audit WHERE room=?",room); db.update("DELETE FROM meridian_rooms WHERE room=?",room);
    return Map.of("ok",true,"state",read(room));
  }); }
  public synchronized Map<String,Object> budget(String room,Limit limit) { room(room); check(limit!=null && limit.limitMinor()!=null && limit.limitMinor()>0 && limit.limitMinor()<=1000000,"Invalid budget limit"); return atomic(()->{
    var state=read(room); var budget=state.getBudgets().stream().filter(b->b.getCategory().equals(limit.category())).findFirst().orElseThrow(()->new ResponseStatusException(HttpStatus.BAD_REQUEST,"Unknown category"));
    budget.setLimit(limit.limitMinor()); save(room,state); audit(room,"budget.updated","",""); return Map.of("ok",true,"state",state);
  }); }
  public synchronized Map<String,Object> events(String room) { room(room); return Map.of("events",db.query("SELECT event_json FROM meridian_audit WHERE room=? ORDER BY sequence DESC LIMIT 100",(r,n)->decode(r.getString(1),Map.class),room)); }
  private List<Intent> intents(String sql,Object...args) { return db.query(sql,(r,n)->new Intent(r.getString("payment_id"),r.getString("room"),r.getString("client_key"),r.getString("payload"),r.getString("phase"),r.getString("provider"),r.getLong("amount")),args); }
  private Payment normalize(Payment p) {
    check(p!=null && p.amountMinor()!=null && p.amountMinor()>=1 && p.amountMinor()<=1000000,"Amount must be integer pence from 1 to 1000000");
    check("card".equals(p.method()) || "bank".equals(p.method()),"Unknown payment method");
    check(fixture.getRecipient(p.recipientId())!=null,"Unknown recipient");
    check(p.note()==null || p.note().length()<=200,"Reference exceeds 200 characters");
    String scenario=p.scenario()==null?"success":p.scenario();
    check(Set.of("success","declined","unavailable","pending").contains(scenario),"Unknown simulation scenario");
    return new Payment(p.recipientId(),p.amountMinor(),p.method(),p.note()==null?"":p.note(),scenario);
  }
  private String payload(Payment p) { return encode(List.of(p.recipientId(),p.amountMinor(),p.method(),p.note())); }
  private long reserved(String room) { Long value=db.queryForObject("SELECT COALESCE(SUM(amount),0) FROM meridian_intents WHERE room=? AND phase IN ('submitting','pending')",Long.class,room); return value==null?0:value; }
  private Intent prepare(String room,String key,Payment p) {
    var state=read(room); var rows=intents("SELECT * FROM meridian_intents WHERE room=? AND client_key=?",room,key);
    if(!rows.isEmpty()) {
      var old=rows.getFirst();
      if(!old.payload().equals(payload(p))) throw new ResponseStatusException(HttpStatus.CONFLICT,"Idempotency key belongs to a different payment");
      if(Set.of("completed","pending","submitting","declined-final").contains(old.status())) return old;
      if(state.getBalance()-reserved(room)<p.amountMinor()) throw new ResponseStatusException(HttpStatus.BAD_REQUEST,"Insufficient available balance");
      db.update("UPDATE meridian_intents SET phase='submitting' WHERE payment_id=?",old.id());
      return new Intent(old.id(),room,key,old.payload(),"prepared",old.provider(),old.amount());
    }
    if(state.getBalance()-reserved(room)<p.amountMinor()) throw new ResponseStatusException(HttpStatus.BAD_REQUEST,"Insufficient available balance");
    String id=UUID.randomUUID().toString(), provider=p.method().equals("card")?"adyen":"worldpay";
    db.update("INSERT INTO meridian_intents(payment_id,room,client_key,payload,phase,provider,amount) VALUES(?,?,?,?,?,?,?)",id,room,key,payload(p),"submitting",provider,p.amountMinor());
    audit(room,"payment.prepared",id,provider);
    return new Intent(id,room,key,payload(p),"prepared",provider,p.amountMinor());
  }
  private Map<String,Object> pending(String id) { return Map.of("ok",false,"error","Payment pending confirmation. Do not create another payment.","code","PAYMENT_PENDING","paymentId",id); }
  private Map<String,Object> completed(Intent intent) {
    var state=read(intent.room()); var txn=state.getTransactions().stream().filter(t->t.getId().equals(intent.id())).findFirst().orElseThrow();
    return Map.of("ok",true,"state",state,"transaction",txn);
  }
  private Map<String,Object> fail(String code,String message) { return Map.of("ok",false,"code",code,"error",message); }
  private Transaction debit(Intent intent,Payment p) {
    var state=read(intent.room()); check(state.getBalance()>=intent.amount(),"Insufficient balance for settlement");
    var recipient=fixture.getRecipient(p.recipientId());
    var transaction=new Transaction(intent.id(),"MER-"+intent.id().substring(0,8).toUpperCase(),p.recipientId(),recipient.getName(),recipient.getCategory(),intent.amount(),fixture.getDemoDate(),intent.provider(),p.method(),"completed",p.note());
    state.setBalance(state.getBalance()-intent.amount()); state.getTransactions().add(transaction); save(intent.room(),state);
    db.update("UPDATE meridian_intents SET phase='completed' WHERE payment_id=?",intent.id()); audit(intent.room(),"payment.completed",intent.id(),intent.provider()); return transaction;
  }
  public synchronized Map<String,Object> payment(String room,String key,Payment input) {
    room(room); check(key!=null && key.matches("[A-Za-z0-9_-]{1,100}"),"Invalid Idempotency-Key"); var p=normalize(input);
    // Commit intent before sending to a provider. Keep the same monitor across both commits.
    Intent intent=atomic(()->prepare(room,key,p));
    if(intent.status().equals("completed")) return atomic(()->completed(intent));
    if(Set.of("pending","submitting").contains(intent.status())) return pending(intent.id());
    if(intent.status().equals("declined-final")) return fail("PAYMENT_DECLINED","Payment was declined by reconciliation");
    PaymentProvider.Outcome outcome;
    try { outcome=providers.get(intent.provider()).authorize(intent.id(),p.scenario(),"UK"); }
    catch(RuntimeException e) { outcome=PaymentProvider.Outcome.PENDING; }
    final var result=outcome;
    return atomic(()->{
      if(result==PaymentProvider.Outcome.SUCCESS) { debit(intent,p); return completed(intent); }
      String phase=result==PaymentProvider.Outcome.PENDING?"pending":result==PaymentProvider.Outcome.DECLINED?"declined":"unavailable";
      db.update("UPDATE meridian_intents SET phase=? WHERE payment_id=?",phase,intent.id()); audit(room,"payment."+phase,intent.id(),intent.provider());
      if(result==PaymentProvider.Outcome.PENDING) return pending(intent.id());
      return fail(result==PaymentProvider.Outcome.DECLINED?"PAYMENT_DECLINED":"PROVIDER_UNAVAILABLE",result==PaymentProvider.Outcome.DECLINED?"Payment declined. No debit was made.":"Provider unavailable before authorization. No debit was made.");
    });
  }
  public synchronized Map<String,Object> webhook(String provider,String timestamp,String signature,String raw) {
    if(webhookSecret.isBlank()) throw new ResponseStatusException(HttpStatus.FORBIDDEN,"Webhook simulation is disabled");
    try {
      long sent=Long.parseLong(timestamp); long now=Instant.now().getEpochSecond();
      if(sent<now-300 || sent>now+300 || signature==null || !signature.matches("[0-9a-f]{64}")) throw new IllegalArgumentException();
      Mac hmac=Mac.getInstance("HmacSHA256"); hmac.init(new SecretKeySpec(webhookSecret.getBytes(StandardCharsets.UTF_8),"HmacSHA256"));
      if(!MessageDigest.isEqual(hmac.doFinal((timestamp+"."+raw).getBytes(StandardCharsets.UTF_8)),HexFormat.of().parseHex(signature))) throw new IllegalArgumentException();
    } catch(Exception e) { throw new ResponseStatusException(HttpStatus.FORBIDDEN,"Invalid webhook signature or timestamp"); }
    Callback event;
    try { event=json.readValue(raw,Callback.class); } catch(Exception e) { throw new ResponseStatusException(HttpStatus.BAD_REQUEST,"Invalid callback body"); }
    room(event.sessionId()); check(providers.containsKey(provider),"Unknown provider");
    check(event.eventId()!=null && event.eventId().matches("[A-Za-z0-9_-]{1,100}"),"Invalid event ID");
    check("completed".equals(event.status()) || "declined".equals(event.status()),"Invalid callback status");
    return atomic(()->{
      String hash;
      try { hash=HexFormat.of().formatHex(MessageDigest.getInstance("SHA-256").digest(encode(event).getBytes(StandardCharsets.UTF_8))); } catch(Exception e) { throw new IllegalStateException(e); }
      var seen=db.query("SELECT payload_hash FROM meridian_callbacks WHERE room=? AND provider=? AND event_id=?",(r,n)->r.getString(1),event.sessionId(),provider,event.eventId());
      if(!seen.isEmpty()) { if(!hash.equals(seen.getFirst())) throw new ResponseStatusException(HttpStatus.CONFLICT,"Event ID payload changed"); return Map.of("ok",true,"duplicate",true); }
      var rows=intents("SELECT * FROM meridian_intents WHERE payment_id=? AND room=?",event.paymentId(),event.sessionId());
      check(!rows.isEmpty(),"Unknown payment intent"); var intent=rows.getFirst(); check(intent.provider().equals(provider),"Callback provider mismatch");
      if(!Set.of("pending","submitting").contains(intent.status())) throw new ResponseStatusException(HttpStatus.CONFLICT,"Payment already has a final outcome");
      if(event.status().equals("completed")) debit(intent,paymentFromStored(intent.payload()));
      else { db.update("UPDATE meridian_intents SET phase='declined-final' WHERE payment_id=?",intent.id()); audit(intent.room(),"payment.declined",intent.id(),provider); }
      db.update("INSERT INTO meridian_callbacks(room,provider,event_id,payload_hash) VALUES(?,?,?,?)",event.sessionId(),provider,event.eventId(),hash);
      return Map.of("ok",true,"duplicate",false);
    });
  }
  private Payment paymentFromStored(String payload) {
    try {
      JsonNode node=json.readTree(payload);
      if(node.isArray()) return new Payment(node.get(0).asText(),node.get(1).longValue(),node.get(2).asText(),node.get(3).asText(),"success");
      return new Payment(node.path("recipientId").asText(),node.path("amountMinor").longValue(),node.path("method").asText(),node.path("note").asText(""),"success");
    } catch(Exception e) { throw new IllegalStateException(e); }
  }
  public synchronized IntentResult createIntent(String room,String key,IntentRequest input) {
    room(room); check(key!=null && key.matches("[A-Za-z0-9_-]{1,100}"),"Invalid Idempotency-Key");
    check(input!=null,"Invalid payment intent");
    check(input.amountMinor()!=null && input.amountMinor()>=1 && input.amountMinor()<=1000000,"Amount must be integer pence from 1 to 1000000");
    check(input.recipientId()!=null && fixture.getRecipient(input.recipientId())!=null,"Unknown recipient");
    check(input.note()==null || input.note().length()<=200,"Reference exceeds 200 characters");
    check(input.descriptor()!=null && input.descriptor().matches("[a-z0-9_]{1,64}"),"Unknown payment method descriptor");
    check("UK".equals(input.corridor()) || "US".equals(input.corridor()),"Unsupported corridor");
    check(input.catalogVersion()!=null && input.catalogVersion().matches("[A-Za-z0-9._-]{1,64}"),"Catalog version is required");
    String scenario=input.scenario()==null?"success":input.scenario();
    check(Set.of("success","declined","unavailable","pending").contains(scenario),"Unknown simulation scenario");
    String note=input.note()==null?"":input.note();
    // Persist the intent, then call the single resolved provider. Never fall back after an ambiguous outcome.
    Intent intent=atomic(()->prepareIntent(room,key,input,note));
    if(Set.of("completed","pending","submitting","declined-final").contains(intent.status())) return atomic(()->intentResult(intent));
    PaymentProvider provider=providers.get(intent.provider());
    PaymentProvider.Outcome outcome;
    try { outcome=provider==null?PaymentProvider.Outcome.PENDING:provider.authorize(intent.id(),scenario,input.corridor()); }
    catch(RuntimeException e) { outcome=PaymentProvider.Outcome.PENDING; }
    final var result=outcome;
    return atomic(()->{
      if(result==PaymentProvider.Outcome.SUCCESS) { debit(intent,paymentFromStored(intent.payload())); return intentResult(reload(intent.id())); }
      String phase=result==PaymentProvider.Outcome.PENDING?"pending":result==PaymentProvider.Outcome.DECLINED?"declined":"unavailable";
      db.update("UPDATE meridian_intents SET phase=? WHERE payment_id=?",phase,intent.id());
      audit(room,"payment."+phase,intent.id(),intent.provider());
      return intentResult(reload(intent.id()));
    });
  }
  public synchronized Map<String,Object> readIntent(String room,String id) {
    room(room); check(id!=null && id.matches("[A-Za-z0-9_-]{1,64}"),"Invalid payment intent id");
    return atomic(()->{
      var rows=intents("SELECT * FROM meridian_intents WHERE payment_id=? AND room=?",id,room);
      if(rows.isEmpty()) throw new ResponseStatusException(HttpStatus.NOT_FOUND,"Unknown payment intent");
      JsonNode node; try { node=json.readTree(rows.getFirst().payload()); } catch(Exception e) { throw new IllegalStateException(e); }
      if(!node.isObject()) throw new ResponseStatusException(HttpStatus.NOT_FOUND,"Unknown payment intent");
      return intentView(rows.getFirst());
    });
  }
  private Intent prepareIntent(String room,String key,IntentRequest input,String note) {
    var state=read(room); var rows=intents("SELECT * FROM meridian_intents WHERE room=? AND client_key=?",room,key);
    if(!rows.isEmpty()) {
      var old=rows.getFirst();
      if(!sameBusiness(old,input,note)) throw new ResponseStatusException(HttpStatus.CONFLICT,"Idempotency key belongs to a different payment");
      if(Set.of("completed","pending","submitting","declined-final").contains(old.status())) return old;
      if(state.getBalance()-reserved(room)<input.amountMinor()) throw new ResponseStatusException(HttpStatus.BAD_REQUEST,"Insufficient available balance");
      db.update("UPDATE meridian_intents SET phase='submitting' WHERE payment_id=?",old.id());
      return new Intent(old.id(),room,key,old.payload(),"prepared",old.provider(),old.amount());
    }
    if(!MethodCatalog.VERSION.equals(input.catalogVersion())) throw new ResponseStatusException(HttpStatus.CONFLICT,"Payment method catalog is stale");
    var resolved=MethodCatalog.resolve(input.descriptor());
    if(resolved==null) throw new ResponseStatusException(HttpStatus.BAD_REQUEST,"Unknown payment method descriptor");
    if(state.getBalance()-reserved(room)<input.amountMinor()) throw new ResponseStatusException(HttpStatus.BAD_REQUEST,"Insufficient available balance");
    String id=UUID.randomUUID().toString();
    String payload=encode(new StoredIntent(input.recipientId(),input.amountMinor(),resolved.legacyMethod(),note,resolved.descriptor(),input.corridor(),input.catalogVersion()));
    db.update("INSERT INTO meridian_intents(payment_id,room,client_key,payload,phase,provider,amount) VALUES(?,?,?,?,?,?,?)",id,room,key,payload,"submitting",resolved.providerId(),input.amountMinor());
    audit(room,"payment.prepared",id,resolved.providerId());
    return new Intent(id,room,key,payload,"prepared",resolved.providerId(),input.amountMinor());
  }
  private boolean sameBusiness(Intent old,IntentRequest input,String note) {
    try {
      JsonNode node=json.readTree(old.payload()); if(!node.isObject()) return false;
      StoredIntent stored=json.treeToValue(node,StoredIntent.class);
      return stored.recipientId().equals(input.recipientId()) && stored.amountMinor()==input.amountMinor() && stored.descriptor().equals(input.descriptor()) && stored.corridor().equals(input.corridor()) && stored.note().equals(note) && stored.catalogVersion().equals(input.catalogVersion());
    } catch(Exception e) { return false; }
  }
  private Intent reload(String id) { return intents("SELECT * FROM meridian_intents WHERE payment_id=?",id).getFirst(); }
  private IntentResult intentResult(Intent intent) { var body=intentView(intent); return new IntentResult(httpFor((String)body.get("status")),body); }
  private int httpFor(String status) { return switch(status) { case "succeeded" -> 200; case "requires_action" -> 202; case "declined" -> 422; case "failed" -> 503; default -> 400; }; }
  private Map<String,Object> intentView(Intent intent) {
    StoredIntent stored=decode(intent.payload(),StoredIntent.class); String phase=intent.status();
    String status=switch(phase) { case "completed" -> "succeeded"; case "pending","submitting","prepared" -> "requires_action"; case "declined","declined-final" -> "declined"; default -> "failed"; };
    String reason=switch(phase) {
      case "completed" -> "Payment completed.";
      case "pending","submitting","prepared" -> "Payment pending confirmation. Do not create another payment.";
      case "declined" -> "Payment declined. No debit was made.";
      case "declined-final" -> "Payment was declined by reconciliation";
      default -> "Provider unavailable before authorization. No debit was made.";
    };
    var body=new LinkedHashMap<String,Object>();
    body.put("id",intent.id()); body.put("status",status); body.put("authoritative",true); body.put("simulation",true);
    body.put("amountMinor",intent.amount()); body.put("currency","GBP"); body.put("descriptor",stored.descriptor());
    body.put("corridor",stored.corridor()); body.put("catalogVersion",stored.catalogVersion());
    body.put("action","requires_action".equals(status)?Map.of("type","await_confirmation","payload",Map.of("intentId",intent.id(),"simulation",true,"clientAction","poll")):null);
    body.put("statusReason",reason);
    if("succeeded".equals(status)) {
      var state=read(intent.room()); var txn=state.getTransactions().stream().filter(t->t.getId().equals(intent.id())).findFirst().orElseThrow();
      body.put("receipt",receipt(txn)); body.put("balanceMinor",state.getBalance());
    }
    return body;
  }
  private Map<String,Object> receipt(Transaction txn) {
    var body=new LinkedHashMap<String,Object>();
    body.put("id",txn.getId()); body.put("reference",txn.getReference()); body.put("recipientId",txn.getRecipientId());
    body.put("name",txn.getName()); body.put("category",txn.getCategory()); body.put("amountMinor",txn.getAmount());
    body.put("date",txn.getDate()); body.put("method",txn.getMethod()); body.put("status",txn.getStatus()); body.put("note",txn.getNote());
    return body;
  }
}
